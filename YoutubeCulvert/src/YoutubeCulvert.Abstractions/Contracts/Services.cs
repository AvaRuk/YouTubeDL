/// <summary>Search and search continuation.</summary>
public interface ISearchService : IPagedService<SearchResult>
{
    Task<SearchPage> SearchAsync(
        string query,
        SearchFilter? filter = null,
        SortOrder sortOrder = SortOrder.Relevance,
        int maxResults = 20,
        CancellationToken ct = default);

    Task<SearchPage> ContinueAsync(
        string continuation,
        SearchFilter? filter = null,
        int maxResults = 20,
        CancellationToken ct = default);

    Task<Result<SearchPage>> TrySearchAsync(
        string query,
        SearchFilter? filter = null,
        SortOrder sortOrder = SortOrder.Relevance,
        int maxResults = 20,
        CancellationToken ct = default);

    Task<IReadOnlyList<string>> GetSuggestionsAsync(string query, CancellationToken ct = default);
}

