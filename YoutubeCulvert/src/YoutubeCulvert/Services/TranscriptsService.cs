using YoutubeCulvert.Caching;
using YoutubeCulvert.Configuration;
using YoutubeCulvert.Http;
using YoutubeCulvert.InnerTube.Endpoints;
using YoutubeCulvert.Url;

namespace YoutubeCulvert.Services;

/// <summary>Subtitles: track list, transcript, translation and plain text.</summary>
public sealed class TranscriptsService : ITranscriptsService
{
    private readonly PlayerEndpoint _player;
    private readonly NextEndpoint _next;
    private readonly CaptionTrackParser _captionParser;
    private readonly TranscriptPanelParser _panelParser;
    private readonly IHttpTransport _http;
    private readonly IYoutubeCache _cache;
    private readonly CacheTtls _ttls;
    private readonly IYoutubeUrlParser _urls;
    private readonly YoutubeClientOptions _options;

    internal TranscriptsService(
        PlayerEndpoint player,
        NextEndpoint next,
        CaptionTrackParser captionParser,
        TranscriptPanelParser panelParser,
        IHttpTransport http,
        IYoutubeCache cache,
        CacheTtls ttls,
        IYoutubeUrlParser urls,
        YoutubeClientOptions options)
    {
        _player = player;
        _next = next;
        _captionParser = captionParser;
        _panelParser = panelParser;
        _http = http;
        _cache = cache;
        _ttls = ttls;
        _urls = urls;
        _options = options;
    }

    public async Task<IReadOnlyList<CaptionTrack>> ListTracksAsync(
        string videoId,
        CancellationToken ct = default)
    {
        var id = _urls.ParseVideoIdOrThrow(videoId);

        var result = await _player
            .ExecuteAsync(new PlayerRequest(id, CacheKeys.Video(id, _options.Language, _options.Region)), ct)
            .ConfigureAwait(false);

        var parsed = _captionParser.Parse(result.Raw);
        return parsed.IsRecognized ? parsed.Items : [];
    }

    public Task<Result<IReadOnlyList<CaptionTrack>>> TryListTracksAsync(
        string videoId,
        CancellationToken ct = default) =>
        ServiceErrors.RunAsync(() => ListTracksAsync(videoId, ct));

    public async Task<TranscriptTrack> GetAsync(
        string videoId,
        string? languageCode = null,
        bool includeAutoGenerated = true,
        CancellationToken ct = default)
    {
        var id = _urls.ParseVideoIdOrThrow(videoId);

        var result = await _player
            .ExecuteAsync(new PlayerRequest(id, CacheKeys.Video(id, _options.Language, _options.Region)), ct)
            .ConfigureAwait(false);

        var parsed = _captionParser.Parse(result.Raw);
        var tracks = parsed.IsRecognized ? parsed.Items : [];

        if (tracks.Count == 0)
            throw new YoutubeException($"Video '{id}' does not provide subtitles.");

        var track = SelectTrack(tracks, languageCode, includeAutoGenerated)
                    ?? throw new YoutubeException(
                        languageCode is null
                            ? $"Video '{id}' has no manually created subtitle track."
                            : $"Video '{id}' has no subtitle track for '{languageCode}'.");

        var segments = track.BaseUrl is { Length: > 0 } baseUrl
            ? await DownloadTimedTextAsync(id, baseUrl, translateTo: null, track, ct).ConfigureAwait(false)
            : [];

        if (segments.Count == 0)
            segments = await DownloadPanelAsync(id, ct).ConfigureAwait(false);

        if (segments.Count == 0)
        {
            throw new YoutubeException(
                $"Failed to download subtitles for video '{id}'.");
        }

        return new TranscriptTrack
        {
            LanguageCode = track.LanguageCode,
            Name = track.Name,
            IsAutoGenerated = track.IsAutoGenerated,
            IsTranslatable = track.IsTranslatable,
            BaseUrl = track.BaseUrl,
            Segments = segments
        };
    }

    public Task<Result<TranscriptTrack>> TryGetAsync(
        string videoId,
        string? languageCode = null,
        bool includeAutoGenerated = true,
        CancellationToken ct = default) =>
        ServiceErrors.RunAsync(() => GetAsync(videoId, languageCode, includeAutoGenerated, ct));

    public async Task<TranscriptTrack> GetTranslatedAsync(
        CaptionTrack track,
        string targetLanguage,
        CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(track);
        ArgumentException.ThrowIfNullOrWhiteSpace(targetLanguage);

        if (track.BaseUrl is not { Length: > 0 } baseUrl)
            throw new ArgumentException("The caption track does not contain a base URL.", nameof(track));

        var videoId = ExtractVideoId(baseUrl) ?? "unknown";
        var segments = await DownloadTimedTextAsync(videoId, baseUrl, targetLanguage, track, ct)
            .ConfigureAwait(false);

        if (segments.Count == 0)
        {
            throw new YoutubeException(
                $"Failed to download a transcript translated to '{targetLanguage}'.");
        }

        return new TranscriptTrack
        {
            LanguageCode = targetLanguage,
            Name = targetLanguage,
            IsAutoGenerated = track.IsAutoGenerated,
            IsTranslatable = track.IsTranslatable,
            BaseUrl = track.BaseUrl,
            Segments = segments
        };
    }

    public Task<Result<TranscriptTrack>> TryGetTranslatedAsync(
        CaptionTrack track,
        string targetLanguage,
        CancellationToken ct = default) =>
        ServiceErrors.RunAsync(() => GetTranslatedAsync(track, targetLanguage, ct));

    public async Task<string> GetTextAsync(
        string videoId,
        string? languageCode = null,
        CancellationToken ct = default)
    {
        var transcript = await GetAsync(videoId, languageCode, true, ct).ConfigureAwait(false);
        return string.Join(' ', transcript.Segments.Select(static segment => segment.Text));
    }

    private static CaptionTrack? SelectTrack(
        IReadOnlyList<CaptionTrack> tracks,
        string? languageCode,
        bool includeAutoGenerated)
    {
        var candidates = includeAutoGenerated
            ? tracks
            : tracks.Where(static track => !track.IsAutoGenerated).ToArray();

        if (candidates.Count == 0)
            return null;

        if (!string.IsNullOrWhiteSpace(languageCode))
        {
            var exact = candidates.FirstOrDefault(track =>
                string.Equals(track.LanguageCode, languageCode, StringComparison.OrdinalIgnoreCase));

            if (exact is not null)
                return exact;

            var prefix = candidates.FirstOrDefault(track =>
                track.LanguageCode.StartsWith(languageCode, StringComparison.OrdinalIgnoreCase) ||
                languageCode.StartsWith(track.LanguageCode, StringComparison.OrdinalIgnoreCase));

            if (prefix is not null)
                return prefix;
        }

        return candidates.FirstOrDefault(static track => !track.IsAutoGenerated) ?? candidates[0];
    }

    private async Task<IReadOnlyList<TranscriptSegment>> DownloadTimedTextAsync(
        string videoId,
        string baseUrl,
        string? translateTo,
        CaptionTrack track,
        CancellationToken ct)
    {
        var url = TranscriptParser.BuildTimedTextUrl(baseUrl, translateTo);
        var cacheKey = CacheKeys.Transcript(
            videoId,
            translateTo ?? track.LanguageCode,
            track.IsAutoGenerated,
            _options.Language,
            _options.Region);

        var cached = await _cache.GetAsync<string>(cacheKey, ct).ConfigureAwait(false);

        if (!string.IsNullOrEmpty(cached))
            return ParseTimedText(cached);

        try
        {
            var body = await _http.GetTextAsync(url, "application/json", ct).ConfigureAwait(false);

            if (string.IsNullOrWhiteSpace(body))
                return [];

            await _cache.SetAsync(cacheKey, body, _ttls.Transcripts, ct).ConfigureAwait(false);
            return ParseTimedText(body);
        }
        catch (YoutubeApiException exception) when ((int)exception.StatusCode != 429)
        {
            // A signed/expired timedtext URL falls back to the transcript panel.
            return [];
        }
    }

    private IReadOnlyList<TranscriptSegment> ParseTimedText(string body) =>
        TimedTextParser.Parse(body).Items;

    private async Task<IReadOnlyList<TranscriptSegment>> DownloadPanelAsync(
        string videoId,
        CancellationToken ct)
    {
        var watchNext = await _next
            .ExecuteAsync(new NextRequest(VideoId: videoId), ct)
            .ConfigureAwait(false);

        var token = TranscriptParser.FindTranscriptContinuation(watchNext.Raw);

        if (token is null)
            return [];

        var transcript = await _next
            .ExecuteAsync(new NextRequest(Continuation: token), ct)
            .ConfigureAwait(false);

        var parsed = _panelParser.Parse(transcript.Raw);
        return parsed.IsRecognized ? parsed.Items : [];
    }

    private static string? ExtractVideoId(string baseUrl)
    {
        if (!Uri.TryCreate(baseUrl, UriKind.Absolute, out var uri))
            return null;

        return YoutubeUrlParser.GetQueryValue(uri, "v");
    }
}
